"""Equipment on Adol: the C drawing (runtime/app/equip.c) matches the Python rules (equip_art.compose).

Usage: python tools\\equip\\equip_c_test.py EQUIP_CHECK OUTPUT.bin
  EQUIP_CHECK = build\\Release\\equip_check.exe (writes the table of the 36 frames and the C drawing of each frame with
  every combination of sword, shield and armor in Ys I and Ys II; tools/equip/equip_check.c)

Checks runtime/app/equip_art.h (sword and shield drawings, generated by equip_art_c.py) and every frame in every
combination (36 x 559), and that the table has the 3 frame sets in the 4 directions, a blade in those with a sword and
a shield in those with a shield; and the ice reflection (equip_ice against equip_art.ice_compose), in the 216
combinations of Ys I. Prints "equip_c_test: OK" or the differences.
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import equip_art as A  # noqa: E402


def rgb(c):
    return ((c >> 3) & 7, (c >> 6) & 7, c & 7)


def check_look(img, px, base, mask, pal, what, errors):
    """The eyes and what surrounds them as in the game; the outline between the blade and the body kept."""
    for y in range(9, 13):
        for x in range(1, 15):
            if base[y][x] == A.OUT and base[y][x - 1] == A.SKIN and base[y][x + 1] == A.SKIN:
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        c = base[y + dy][x + dx]
                        if img[y + dy][x + dx] != (pal[c] if c else None) and len(errors) < 10:
                            errors.append(f"{what}: touched the eye at {x + dx},{y + dy}")
    for (x, y) in [p for p in A.blade_pixels(px) if p not in mask][2:]:  # away from the base, where the guard goes
        for d in (-1, 1):
            X, far = x + d, x + 2 * d
            if (0 <= far < 16 and px[y][X] == A.OUT and px[y][far] not in (0, A.OUT, A.BLADE)
                    and img[y][X] != pal[A.OUT] and len(errors) < 10):
                errors.append(f"{what}: blade without outline at {X},{y}")


def check_ice_colors(pal, frames, errors):
    """On the ice, pieces keep their color: a piece's yellow, equal to a color in the game palette, does not turn orange."""
    st, d, px, mask, under, shadow = frames[12]
    img = A.compose(px, pal, d, "Long Sword", None, "Reflex", "ys1", frozenset(), under, 0)
    ice = A.ice_compose(img, shadow, pal, px)
    pts = [(x, y) for y in range(24) for x in range(16) if img[y][x] == (7, 6, 0) and px[y][x] != 12]
    if not pts or any(ice[y][x] != (7, 7, 0) for (x, y) in pts):
        errors.append(f"piece yellow on the ice:{[ice[y][x] for (x, y) in pts][:4]}")


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    exe, out = sys.argv[1:3]
    subprocess.run([exe, out], check=True, stdout=subprocess.DEVNULL)
    data = open(out, "rb").read()
    words = struct.unpack(f"<{len(data) // 2}H", data)
    o = 0
    pal = [rgb(c) for c in words[o:o + 16]]
    o += 16
    ice_pal = [rgb(c) for c in words[o:o + 16]]
    o += 16
    frames = []
    for _ in range(36):
        st, d = words[o], words[o + 1]
        o += 2
        px = [list(words[o + y * 16:o + y * 16 + 16]) for y in range(32)]
        o += 512
        mask = frozenset((x, y) for y in range(32) for x in range(16) if (words[o + y] >> x) & 1)
        o += 32
        b7 = [(x, y) for y in range(32) for x in range(16) if (words[o + y] >> x) & 1]
        o += 32
        under = [list(words[o + y * 16:o + y * 16 + 16]) for y in range(32)]
        o += 512
        shadow = frozenset((x, y) for y in range(32) for x in range(16) if (words[o + y] >> x) & 1)
        o += 32
        for (x, y) in b7:
            px[y][x] = A.BLADE
        frames.append((st, d, px, mask, under, shadow))
    errors = []
    if tuple(ice_pal) != tuple(A.ICE_PAL):
        errors.append(f"different ice palette: {ice_pal}")
    # the sword and shield drawings in C (equip_art.h, generated) equal those in equip_art.py
    if subprocess.run([sys.executable, os.path.join(HERE, "equip_art_c.py"), "--check"]).returncode:
        errors.append("runtime/app/equip_art.h out of date")
    # the table: 12 frames per set, 3 per direction; a blade in every sword-only frame and in none without a sword
    # (with a shield, in a step to the left the sword is behind the body); a shield only in those with a shield
    for i, (st, d, px, mask, under, shadow) in enumerate(frames):
        if st != i // 12 or d != (i % 12) // 3:
            errors.append(f"frame {i}: set {st} direction {d}")
        blade = bool(A.blade_pixels(px))
        if (st == 0 and blade) or (st == 1 and not blade) or bool(mask) != (st == 2):
            errors.append(f"frame {i}: blade/shield out of place")
    check_ice_colors(pal, frames, errors)
    images = ice_images = bad = 0

    def compare(c, py, what):
        nonlocal bad
        diff = [(x, y) for y in range(32) for x in range(16)
                if (None if c[y * 16 + x] == 0xFFFF else rgb(c[y * 16 + x])) != py[y][x]]
        if diff:
            bad += 1
            if len(errors) < 10:
                errors.append(f"{what}: {len(diff)} pixels, e.g. {diff[:4]}")

    for game in ("ys1", "ys2"):
        items = A.ITEMS[game]
        for s in [None] + items["sword"]:
            for h in [None] + items["shield"]:
                for a in [None] + items["armor"]:
                    for i, (st, d, px, mask, under, shadow) in enumerate(frames):
                        py = A.compose(px, pal, d, s, h, a, game, mask, under, i % 3)
                        compare(words[o:o + 512], py, f"{game} {s} / {h} / {a}, frame {i}")
                        o += 512
                        images += 1
                        check_look(py, px, under if st == 2 else px, mask, pal,
                                   f"{game} {s} / {h} / {a}, frame {i}", errors)
                        if game == "ys1":
                            compare(words[o:o + 512], A.ice_compose(py, shadow, pal, px, under if st == 2 else None),
                                    f"ice {s} / {h} / {a}, frame {i}")
                            o += 512
                            ice_images += 1
    if o != len(words):
        errors.append(f"file has {len(words) - o} extra words")
    print(f"equip_c_test: {images} images and {ice_images} on the ice, {bad} different")
    for e in errors:
        print("  " + e)
    if errors or images != 36 * (6 * 6 * 6 + 7 * 7 * 7) or ice_images != 36 * 6 * 6 * 6:
        print("equip_c_test: FAILED")
        return 1
    print("equip_c_test: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
