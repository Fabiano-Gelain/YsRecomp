"""Adol's frames for the equipment in the window: generates the C with the 36 frames (runtime/app/equip.h, EquipTable).

Usage: python tools\\equip\\equip_frames.py PCE_TRACE CUE BIOS OUTPUT.c
  (CMake generates games\\ys\\generated\\equip\\equip_frames.c, outside Git: it holds the game's drawings)

The frames come from the player's disc, as in the preview (equip_preview.load_frames: the session
games\\ys\\sessions\\session_20261017_153505 with the BIOS, in the three frame sets): no sword, with sword and with
sword and shield, each with the 4 directions x (standing, step 1, step 2). For each frame: the color indices as
they are in VRAM (the window recognizes Adol by them), the game shield's pixels (mask) and the blade pixels painted in
color 7 (blade7); with a shield, the sword-only frame in the same pose (under). The reference palette 13 is the one of
the rules (equip_art.py).
"""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import equip_art as A  # noqa: E402
import equip_ice_preview as I  # noqa: E402
import equip_preview as P  # noqa: E402

SETS = ["nosword", "sword", "ss"]  # in the order of EQUIP_SET_*


def vce(rgb):
    r, g, b = rgb
    return (g << 6) | (r << 3) | b


def bits(points, y):
    return sum(1 << x for (x, yy) in points if yy == y)


def table(sets, pal, masks, ice):
    """List of (set, dir, pose, px, mask, blade7, under, ice_shadow) in the C order"""
    shadows = {"sword": [I.shadow_of(sets["sword"][i], ice["sword"][i]) for i in range(12)],
               "ss": [I.shadow_of(sets["ss_vram"][i], ice["ss"][i]) for i in range(12)]}
    shadows["nosword"] = shadows["sword"]  # there are no ice frames without a sword in a session (docs/ys_notes.md)
    out = []
    for si, name in enumerate(SETS):
        for i, (d, k) in enumerate(P.FRAMES):
            px = sets["ss_vram"][i] if name == "ss" else sets[name][i]
            mask = masks[i] if name == "ss" else frozenset()
            b7 = {(x, y) for y in range(32) for x in range(16)
                  if name == "ss" and sets["ss"][i][y][x] == A.BLADE and px[y][x] == 7}
            under = sets["sword"][i] if name == "ss" else [[0] * 16 for _ in range(32)]
            out.append((si, d, k, px, mask, b7, under, shadows[name][i]))
    return out


def write_c(path, pal, ice_pal, frames):
    lines = ["/* Generated by tools/equip/equip_frames.py from the player's disc: do not version. */",
             '#include "app/equip.h"', "", "static const EquipTable k_table = {",
             "    { " + ", ".join(str(vce(c)) for c in pal) + " },",
             "    { " + ", ".join(str(vce(c)) for c in ice_pal) + " },", "    {"]
    for si, d, k, px, mask, b7, under, shadow in frames:
        rows = ", ".join("{ " + ", ".join(str(c) for c in r) + " }" for r in px)
        urows = ", ".join("{ " + ", ".join(str(c) for c in r) + " }" for r in under)
        lines.append(f"        {{ {si}, {d}, {k}, {{ {rows} }},")
        lines.append("          { " + ", ".join(str(bits(mask, y)) for y in range(32)) + " },")
        lines.append("          { " + ", ".join(str(bits(b7, y)) for y in range(32)) + " },")
        lines.append(f"          {{ {urows} }},")
        lines.append("          { " + ", ".join(str(bits(shadow, y)) for y in range(32)) + " } },")
    lines += ["    },", "};", "", "const EquipTable *const g_equip_table = &k_table;", ""]
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        return 2
    pce_trace, cue, bios, out = sys.argv[1:5]
    with tempfile.TemporaryDirectory() as tmp:
        sets, pal, masks = P.load_frames(os.path.abspath(pce_trace), os.path.abspath(cue), os.path.abspath(bios), tmp)
        ice = P.load_ice(os.path.abspath(pce_trace), os.path.abspath(cue), tmp)
    frames = table(sets, pal, masks, ice)
    if len(frames) != 36 or any(not any(any(c for c in r) for r in f[3]) for f in frames):
        print("equip_frames: empty frame (did the disc or the session change?)")
        return 1
    write_c(out, pal, ice["pal14"], frames)
    print(f"equip_frames: {len(frames)} frames in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
