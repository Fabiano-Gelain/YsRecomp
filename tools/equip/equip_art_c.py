"""Sword and shield drawings (equip_art.py) for the C side: generates runtime/app/equip_art.h (versioned: they are
hand-made drawings, nothing from the disc).

Usage: python tools\\equip\\equip_art_c.py            (rewrites runtime/app/equip_art.h)
       python tools\\equip\\equip_art_c.py --check    (only checks that it is up to date; used by the equip_c_ys test)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "runtime", "app", "equip_art.h")
sys.path.insert(0, HERE)
import equip_art as A  # noqa: E402

GAMES = ("ys1", "ys2")


def vce(rgb):
    r, g, b = rgb
    return (g << 6) | (r << 3) | b


def arr(vals):
    return "{ " + ", ".join(str(v) for v in vals) + " }"


def sword_c(sp):
    K = len(sp["blade"])
    side = [lambda s: [vce(A.SW_COLORS[c]) if c != "." else -1 for c in s] + [-1] * (A.BLADE_FULL - K)]
    b = [vce(A.SW_COLORS[c]) for c in sp["blade"]] + [0] * (A.BLADE_FULL - K)
    s1 = side[0](sp["side"]) if sp.get("side") else [-1] * A.BLADE_FULL
    s2 = side[0](sp["side2"]) if sp.get("side2") else [-1] * A.BLADE_FULL
    return (f"{{ {K}, {arr(b)}, {arr(s1)}, {arr(s2)}, {vce(sp['guard'])}, {int(bool(sp.get('guard2')))}, "
            f"{int(bool(sp.get('curve')))}, {vce(sp['hilt'])} }}")


def shield_c(sh):
    rows = []
    for r in sh["front"]:
        assert len(r) == 8
        rows.append(arr(-1 if c == "." else -2 if c == "o" else vce(A.SH_COLORS[c]) for c in r))
    assert len(rows) == 12
    t = sh.get("trim", (0, 0))
    return ("{ {\n        " + ",\n        ".join(rows) + " },\n      "
            f"{arr(t)}, {arr(vce(c) for c in sh['face'])}, {vce(sh['rim'][0])}, {vce(sh['hl'][0])}, "
            f"{arr(vce(c) for c in sh['emblem'])} }}")


def armor_c(sp):
    parts = arr(arr(vce(c) for c in sp[p]) for p in A.ARMOR_PARTS)
    mesh = sum(1 << A.ARMOR_PARTS.index(p) for p in sp.get("mesh", ""))
    h, col = sp.get("horns", (0, (0, 0, 0)))
    gem = sp.get("gem")
    return (f"{{ {parts}, {mesh}, {int(bool(sp.get('pad')))}, {int(bool(sp.get('y')))}, {h}, {vce(col)}, "
            f"{int(bool(gem))}, {arr(vce(c) for c in gem) if gem else '{ 0, 0 }'} }}")


def render():
    L = ["/* Generated by tools/equip/equip_art_c.py from tools/equip/equip_art.py (hand-drawn swords, shields and",
         " * armors): do not edit; change equip_art.py and run the script. Only for equip.c. */",
         "#ifndef APP_EQUIP_ART_H", "#define APP_EQUIP_ART_H", "", "#include <stdint.h>", "",
         f"#define ART_BLADE_FULL {A.BLADE_FULL}",
         "#define ART_KEEP (-1) /* front drawing of the shield: whatever is underneath */",
         "#define ART_OUT (-2)  /* outline */",
         f"#define ART_FRONT_X0 {A.FRONT_X0}", f"#define ART_FRONT_Y0 {A.FRONT_Y0}",
         f"#define ART_FACE_X {A.FRONT_FACE[0]}", f"#define ART_FACE_Y {A.FRONT_FACE[1]}", "",
         "/* Sword: blade pixels (out of 10), colors from the hand to the tip, beside it (-1 = none), guard, wide guard,",
         " * curved blade, hilt (VCE colors) */",
         "typedef struct SwordArt {", "    int n;", "    int16_t blade[ART_BLADE_FULL], side[ART_BLADE_FULL], "
         "side2[ART_BLADE_FULL];", "    int16_t guard;", "    uint8_t guard2, curve;", "    int16_t hilt;",
         "} SwordArt;", "",
         "/* Shield: front drawing (rows 12-23, columns 8-15), rows removed from the side strip (out of 8), strip colors",
         " * by role (face dark/mid/light, rim, highlight, emblem) */",
         "typedef struct ShieldArt {", "    int16_t front[12][8];", "    uint8_t trim[2];",
         "    int16_t face[3], rim, hl, emblem[3];", "} ShieldArt;", "",
         "/* columns of the game's shield in each direction */",
         "static const uint8_t k_shield_cols[4][2] = " + arr(arr(A.SHIELD_COLS[d]) for d in range(4)) + ";", "",
         "static const SwordArt k_sword_art[2][6] = {"]
    for g in GAMES:
        L.append("    {")
        for name in A.ITEMS[g]["sword"]:
            L.append(f"      /* {name} */")
            L.append("      " + sword_c(A.SWORDS[g][name]) + ",")
        L.append("    },")
    L += ["};", "", "static const ShieldArt k_shield_art[2][6] = {"]
    for g in GAMES:
        L.append("    {")
        for name in A.ITEMS[g]["shield"]:
            L.append(f"      /* {name} */")
            L.append("      " + shield_c(A.SHIELDS[g][name]) + ",")
        L.append("    },")
    L += ["};", "",
          "/* Armor: 3 colors (dark, mid, light) for each body part, mesh parts (bits), wide shoulder pad,",
          ' * chest "Y", spike height and color, gem (dark, highlight) */',
          f'#define ART_PARTS "{A.ARMOR_PARTS}"',
          f"#define ART_PART_S {A.ARMOR_PARTS.index('S')}", f"#define ART_PART_C {A.ARMOR_PARTS.index('C')}",
          f"#define ART_ROLES_TOP {A.ARMOR_ROLES_TOP}",
          "typedef struct ArmorArt {", f"    int16_t part[{len(A.ARMOR_PARTS)}][3];", "    uint8_t mesh, pad, y, horn_h;",
          "    int16_t horn_col;", "    uint8_t has_gem;", "    int16_t gem[2];", "} ArmorArt;", "",
          "/* no armor */", "static const ArmorArt k_no_armor_art = " + armor_c(A.NONE) + ";", "",
          "static const ArmorArt k_armor_art[2][6] = {"]
    for g in GAMES:
        L.append("    {")
        for name in A.ITEMS[g]["armor"]:
            L.append(f"      /* {name} */")
            L.append("      " + armor_c(A.ARMORS[g][name]) + ",")
        L.append("    },")
    L += ["};", "", "/* The body part of each pixel, by direction and pose, on rows ART_ROLES_TOP onward */",
          "static const char k_armor_roles[4][3][11][17] = {"]
    for d in range(4):
        L.append("    {")
        for k in range(3):
            L.append("      { " + ", ".join(f'"{r}"' for r in A.ARMOR_ROLES[(d, k)]) + " },")
        L.append("    },")
    L += ["};", "", "#endif", ""]
    return "\n".join(L)


def main():
    text = render()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old.replace("\r\n", "\n") != text:
            print("equip_art_c: runtime/app/equip_art.h is out of date (run python tools\\equip\\equip_art_c.py)")
            return 1
        print("equip_art_c: up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"equip_art_c: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
