/* Visible equipment on Adol: each sword, shield and armor of Ys I and Ys II drawn on Adol on the map.
 *
 * Window only: the console does not change (traces and lockstep the same). The game has three sets of 12 frames of small Adol
 * (16x32, sprite palette 13): without sword, with a generic sword and with sword and shield (docs/ys_notes.md,
 * "Equipment on Adol"). The window finds Adol's sprite through the character the game created as the hero (YsList.hero),
 * sees which of the 36 frames it shows (extracted from the player's
 * disc at build time by tools/equip/equip_frames.py, outside Git: EquipTable) and replaces its pixels with the
 * equipment's, with the rules of tools/equip/equip_art.py ported to C (equip_compose; the hand-drawn
 * swords and shields come from there through the equip_art.h generated by tools/equip/equip_art_c.py; the test equip_c_ys checks
 * both on all frames and pieces). The equipment comes from RAM ($2C71-$2C73) and the game (Ys I or II) from the table of the
 * 1st item of each type in CD RAM ($82:6321), read at the end of each frame (equip_read). */
#ifndef APP_EQUIP_H
#define APP_EQUIP_H

#include <stdint.h>

struct Pce;
struct YsFadeFrame;

#define EQUIP_FRAMES 36
#define EQUIP_W 16
#define EQUIP_H 32

enum { EQUIP_SET_NOSWORD, EQUIP_SET_SWORD, EQUIP_SET_SS }; /* without sword, with sword, with sword and shield */
enum { EQUIP_GAME_NONE, EQUIP_GAME_YS1, EQUIP_GAME_YS2 };

typedef struct EquipFrame {
    uint8_t set, dir, pose;             /* EQUIP_SET_*; direction: 0 facing front, 1 facing back, 2 right, 3 left */
    uint8_t px[EQUIP_H][EQUIP_W];  /* color indices as in VRAM (0 = transparent) */
    uint16_t mask[EQUIP_H];        /* pixels of the game's shield (bit x = column x) */
    uint16_t blade7[EQUIP_H];      /* blade pixels painted in color 7 (one step with shield): they count as blade */
    uint8_t under[EQUIP_H][EQUIP_W]; /* with shield: the sword-only frame in the same pose (the body under the
                                      * front-facing shield, for a shield smaller than the game's); otherwise zeros */
    uint16_t ice_shadow[EQUIP_H];  /* on ice: the outline pixels the game removes in this pose (the shadow); without
                                    * sword, the game's ones with sword */
} EquipFrame;

typedef struct EquipTable {
    uint16_t pal[16]; /* reference palette 13 (VCE colors), the rules' one */
    uint16_t ice_pal[16]; /* reference palette 14: the one of Adol and of the reflection on ice */
    EquipFrame frame[EQUIP_FRAMES];
} EquipTable;

/* What is equipped in a frame: sword, shield, armor (piece number, 0xFF = nothing) and the game (EQUIP_GAME_*) */
typedef struct EquipInfo {
    uint8_t sword, shield, armor, game;
} EquipInfo;

/* Frame with the equipment: 32 x 16 VCE colors (9 bits), -1 = transparent */
typedef int16_t EquipImage[EQUIP_H * EQUIP_W];

#define EQUIP_CACHE 4
typedef struct Equip {
    const EquipTable *table;
    struct {
        int frame;
        int ice; /* with the reflection on ice */
        EquipInfo info;
        EquipImage img;
    } cache[EQUIP_CACHE];
    int cache_next;
    uint16_t out[EQUIP_CACHE][EQUIP_H * EQUIP_W]; /* returned by equip_sprite */
    int out_next;
    long shown; /* sprites replaced (ys_trace) */
} Equip;

/* The frames from the disc (generated equip_frames.c); NULL where they were not generated */
extern const EquipTable *const g_equip_table;

void equip_init(Equip *q, const EquipTable *table);

/* Equipment and game at the end of the frame; game = EQUIP_GAME_NONE outside the game or with invalid numbers */
void equip_read(const struct Pce *pce, EquipInfo *out);

/* Pieces of each type in the game (0 = unknown game); kind: 0 sword, 1 shield, 2 armor */
int equip_count(int game, int kind);

/* Frame f (indices, in px; mask and blade7 as in EquipFrame) with palette pal (VCE colors) and the pieces (0xFF =
 * nothing), like equip_art.compose */
void equip_compose(const EquipFrame *f, const uint16_t *pal, const EquipInfo *info, EquipImage out);

/* Reflection on ice (equip_art.ice_compose; docs/ys_notes.md, "Ice reflection"): the equip_compose image becomes the
 * one of Adol on the ice: without the shadow, palette 14 colors and, on lines 24-30, the reflection of his lines */
void equip_ice(const EquipFrame *f, const uint16_t *pal, const uint16_t *ice_pal, EquipImage io);

/* The frame (0..EQUIP_FRAMES-1) that sprite e (4 table words, 16x32) shows in VRAM vram; -1 = none of the 36 */
int equip_frame_of(const EquipTable *table, const uint16_t *vram, const uint16_t *e);

/* Adol's sprite on ice: drawing 10-1F that the engine requests ($2EF8) in palette 14. Returns the frame (0..11) of the same
 * direction and step, within the frame set; -1 = it is not */
int equip_ice_pose(int pose, const uint16_t *e);

/* Check (--equip-log): pixels where the ice rule, with the game's frame fr, differs from sprite e and VRAM */
int equip_ice_diff(const EquipFrame *fr, const uint16_t *vram, const uint16_t *e);

/* The equipment's colors in a frame, read from Adol's palette (13; on ice, 14) and from the game's fade routine
 * (app/ys_fade.h) */
enum {
    EQUIP_COLORS_NONE, /* the game set another palette (effect): Adol comes out as on the console */
    EQUIP_COLORS_MAP,  /* Adol's colors, full or at a level and brightening of the fade routine */
    EQUIP_COLORS_FLAT  /* all colors equal (Adol all white or all black): the equipment too */
};
typedef struct EquipColorSet {
    uint8_t kind;
    uint8_t map[8];     /* each channel value (0-7) as it comes out of the game's fade table */
    uint16_t flat;      /* the single color */
} EquipColorSet;
typedef struct EquipColors {
    uint8_t kind;
    uint8_t map[8];     /* palette 13 (like EquipColorSet) */
    uint16_t flat;
    EquipColorSet ice;  /* palette 14: on ice */
} EquipColors;
void equip_colors(const EquipTable *table, const struct YsFadeFrame *fade, EquipColors *out);

/* Sprite e (4 table words) of VRAM vram, already known to be Adol's character (app/ys_engine.h, YsList.hero, with
 * the drawing pose the engine requested): if it shows one of the known frames or is Adol on ice and info is valid, its image
 * with the equipment in the colors colors, line by line in VRAM order (without the flips): 0 = transparent, otherwise
 * 0x8000 | VCE color; NULL = draw as the console does. The pointer is valid until EQUIP_CACHE calls later. */
const uint16_t *equip_sprite(Equip *q, const EquipInfo *info, const EquipColors *colors, const uint16_t *vram,
                             const uint16_t *e, int pose);

#endif
