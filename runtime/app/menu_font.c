static int fallback(char ch, uint8_t rows[8])
{
    for (size_t i = 0; i < sizeof(k_letters) / sizeof(k_letters[0]); i++)
        if (k_letters[i].ch == ch) {
            memcpy(rows, k_letters[i].rows, 8);
            return 1;
        }
    return 0;
}

int menu_font_glyph(char ch, uint8_t rows[8])
{
    if (ch >= 'a' && ch <= 'z')
        ch = (char)(ch - 'a' + 'A');
    memset(rows, 0, 8);
    for (size_t i = 0; i < sizeof(k_signs) / sizeof(k_signs[0]); i++)
        if (k_signs[i].ch == ch) {
            memcpy(rows, k_signs[i].rows, 8);
            return 1;
        }
    if (g_ready) {
        int k = ch >= '0' && ch <= '9' ? ch - '0'
                : ch == ':'            ? 10
                : ch == '/'            ? 11
                : ch >= 'A' && ch <= 'C' ? 12 + (ch - 'A')
                : ch >= 'D' && ch <= 'Z' ? 16 + (ch - 'D')
                                         : -1;
        if (k >= 0) {
            tile_rows(k, rows);
            return 1;
        }
    }
    return fallback(ch, rows);
}

void menu_font_arrow(uint8_t rows[8])
{
    static const uint8_t k_triangle[8] = { 0x20, 0x30, 0x38, 0x3C, 0x38, 0x30, 0x20, 0x00 };
    if (g_ready)
        tile_rows(MENU_FONT_TILES, rows);
    else
        memcpy(rows, k_triangle, 8);
}
