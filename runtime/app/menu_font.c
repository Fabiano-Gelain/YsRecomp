static uint16_t g_words[MENU_FONT_WORDS]; /* tiles 449-487 and the little arrow, as in VRAM */
static int g_ready;

static uint32_t crc32_words(const uint16_t *w, int n)
{
    uint32_t crc = 0xFFFFFFFFu;
    for (int i = 0; i < n * 2; i++) {
        crc ^= (uint8_t)(i & 1 ? w[i / 2] >> 8 : w[i / 2]);
        for (int k = 0; k < 8; k++)
            crc = crc & 1 ? (crc >> 1) ^ 0xEDB88320u : crc >> 1;
    }
    return ~crc;
}

static int take(const uint16_t *words)
{
    if (crc32_words(words, MENU_FONT_WORDS) != MENU_FONT_CRC)
        return 0;
    memcpy(g_words, words, sizeof(g_words));
    g_ready = 1;
    return 1;
}

int menu_font_capture(const uint16_t *vram)
{
    uint16_t w[MENU_FONT_WORDS];
    memcpy(w, &vram[MENU_FONT_FIRST * 16], MENU_FONT_TILES * 16 * sizeof(uint16_t));
    memcpy(&w[MENU_FONT_TILES * 16], &vram[MENU_FONT_ARROW * 16], 16 * sizeof(uint16_t));
    return take(w);
}

int menu_font_ready(void) { return g_ready; }

void menu_font_forget(void) { g_ready = 0; }

int menu_font_load(const char *path)
{
    uint8_t b[MENU_FONT_WORDS * 2];
    FILE *f = u8_fopen(path, "rb");
    if (!f)
        return -1;
    size_t n = fread(b, 1, sizeof(b), f);
    fclose(f);
    if (n != sizeof(b))
        return -1;
    uint16_t w[MENU_FONT_WORDS];
    for (int i = 0; i < MENU_FONT_WORDS; i++)
        w[i] = (uint16_t)(b[i * 2] | b[i * 2 + 1] << 8);
    return take(w) ? 0 : -1;
}

int menu_font_save(const char *path)
{
    if (!g_ready)
        return -1;
    uint8_t b[MENU_FONT_WORDS * 2];
    for (int i = 0; i < MENU_FONT_WORDS; i++) {
        b[i * 2] = (uint8_t)g_words[i];
        b[i * 2 + 1] = (uint8_t)(g_words[i] >> 8);
    }
    FILE *f = u8_fopen(path, "wb");
    if (!f)
        return -1;
    size_t n = fwrite(b, 1, sizeof(b), f);
    return fclose(f) == 0 && n == sizeof(b) ? 0 : -1;
}

/* Tile k of the copy (0-38; MENU_FONT_TILES = the little arrow): lit pixel = any plane */
static void tile_rows(int k, uint8_t rows[8])
{
    const uint16_t *t = &g_words[k * 16];
    for (int r = 0; r < 8; r++)
        rows[r] = (uint8_t)((t[r] | t[r] >> 8 | t[8 + r] | t[8 + r] >> 8) & 0xFF);
}

